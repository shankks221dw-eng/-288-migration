function t(key, lang) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return dict[key] || TRANSLATIONS.en[key] || key;
}

function detectLanguage() {
  const saved = localStorageSafeGet("s288_lang");
  if (saved && TRANSLATIONS[saved]) return saved;
  const nav = (navigator.language || "en").toLowerCase();
  const short = nav.split("-")[0];
  if (TRANSLATIONS[short]) return short;
  return "en";
}

// Artifacts sandbox note: this file is meant to run on a real static host
// (GitHub Pages/Netlify/Cloudflare Pages), where localStorage is available.
function localStorageSafeGet(key) {
  try { return window.localStorage.getItem(key); } catch (e) { return null; }
}
function localStorageSafeSet(key, val) {
  try { window.localStorage.setItem(key, val); } catch (e) { /* ignore */ }
}
